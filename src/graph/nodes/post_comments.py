from __future__ import annotations

from src.github.client import GitHubClient
from src.graph.state import ReviewState


def _format_review_body(state: ReviewState) -> str:
    """Format the review summary for the PR comment."""
    lines = ["## Code Watcher Review\n"]

    if state["review_summary"]:
        lines.append(state["review_summary"])
        lines.append("")

    # Summary stats
    total = len(state["all_findings"])
    critical = sum(1 for f in state["all_findings"] if f.severity == "critical")
    warnings = sum(1 for f in state["all_findings"] if f.severity == "warning")
    suggestions = sum(1 for f in state["all_findings"] if f.severity == "suggestion")
    nits = sum(1 for f in state["all_findings"] if f.severity == "nit")

    lines.append(f"**Findings**: {total} total")
    if critical:
        lines.append(f"- Critical: {critical}")
    if warnings:
        lines.append(f"- Warning: {warnings}")
    if suggestions:
        lines.append(f"- Suggestion: {suggestions}")
    if nits:
        lines.append(f"- Nit: {nits}")
    lines.append("")

    if state["approved_fixes"]:
        lines.append(f"**Auto-fixes applied**: {len(state['approved_fixes'])}")
        lines.append("")

    if state["human_feedback"]:
        lines.append(f"**Reviewer notes**: {state['human_feedback']}")
        lines.append("")

    lines.append(f"**Overall confidence**: {state['overall_confidence']:.2f}")
    lines.append("")
    lines.append("---")
    lines.append("*Generated by Code Watcher*")

    return "\n".join(lines)


def _format_inline_comments(state: ReviewState) -> list[dict]:
    """Format findings as inline PR comments."""
    comments = []
    for finding in state["all_findings"]:
        if finding.severity in ("critical", "warning"):
            comments.append({
                "path": finding.file_path,
                "line": finding.line,
                "body": f"[{finding.severity.upper()}] {finding.message}",
            })
    return comments


async def post_comments_node(state: ReviewState) -> dict:
    """Post review comments back to GitHub PR."""
    body = _format_review_body(state)
    comments = _format_inline_comments(state)

    github = GitHubClient()
    try:
        await github.post_review(
            state["owner"],
            state["repo"],
            state["pr_number"],
            body=body,
            comments=comments,
            event="COMMENT",
        )
    except Exception:
        # If posting fails, we still complete the workflow
        pass
    finally:
        await github.close()

    return {"phase": "done"}
